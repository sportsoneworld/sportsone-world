/* ==========================================================================
   SportsOne — site JavaScript

   Five small jobs and nothing else: the sports dropdowns, the mobile menu,
   the carousels, the live-scores filter and the "copy link" button.
   Every one of them is an enhancement — the site is complete HTML and CSS
   generated by Hugo and works with JavaScript switched off.
   ========================================================================== */
(function () {
  'use strict';

  var reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ==================================================== sports dropdowns ==
     Hover and keyboard focus are handled in CSS. This adds the click/tap
     behaviour and keeps aria-expanded honest. */

  var openMenu = null;

  function closeMenu() {
    if (!openMenu) return;
    openMenu.item.classList.remove('is-open');
    openMenu.button.setAttribute('aria-expanded', 'false');
    openMenu = null;
  }

  Array.prototype.forEach.call(document.querySelectorAll('[data-submenu]'), function (button) {
    var item = button.closest('.mainnav__item');
    if (!item) return;

    button.addEventListener('click', function (e) {
      e.preventDefault();
      var isOpen = item.classList.contains('is-open');
      closeMenu();
      if (!isOpen) {
        item.classList.add('is-open');
        button.setAttribute('aria-expanded', 'true');
        openMenu = { item: item, button: button };
      }
    });
  });

  document.addEventListener('click', function (e) {
    if (openMenu && !openMenu.item.contains(e.target)) closeMenu();
  });

  document.addEventListener('keydown', function (e) {
    if (e.key !== 'Escape' || !openMenu) return;
    var button = openMenu.button;
    closeMenu();
    button.focus();
  });

  /* ========================================================= mobile menu == */

  var drawer = document.getElementById('site-drawer');
  if (drawer) {
    var opener = document.querySelector('[data-drawer-open]');
    var panel = drawer.querySelector('.drawer__panel');

    function focusable() {
      return Array.prototype.slice.call(
        panel.querySelectorAll('a[href], button:not([disabled]), input, [tabindex]:not([tabindex="-1"])')
      ).filter(function (el) { return el.offsetParent !== null; });
    }

    function setDrawer(open) {
      drawer.setAttribute('data-open', open ? 'true' : 'false');
      document.body.classList.toggle('is-locked', open);
      if (opener) {
        opener.setAttribute('aria-expanded', open ? 'true' : 'false');
        opener.setAttribute('aria-label', open ? 'Close menu' : 'Open menu');
      }
      if (open) {
        var f = focusable();
        if (f.length) f[0].focus();
      } else if (opener) {
        opener.focus();
      }
    }

    if (opener) {
      opener.addEventListener('click', function () {
        setDrawer(drawer.getAttribute('data-open') !== 'true');
      });
    }

    Array.prototype.forEach.call(drawer.querySelectorAll('[data-drawer-close]'), function (el) {
      el.addEventListener('click', function () { setDrawer(false); });
    });

    /* Expanding sport rows inside the menu */
    Array.prototype.forEach.call(drawer.querySelectorAll('[data-accordion]'), function (button) {
      var sub = document.getElementById(button.getAttribute('aria-controls'));
      if (!sub) return;
      button.addEventListener('click', function () {
        var open = button.getAttribute('aria-expanded') === 'true';
        button.setAttribute('aria-expanded', open ? 'false' : 'true');
        if (open) sub.setAttribute('hidden', ''); else sub.removeAttribute('hidden');
      });
    });

    document.addEventListener('keydown', function (e) {
      if (drawer.getAttribute('data-open') !== 'true') return;
      if (e.key === 'Escape') { setDrawer(false); return; }
      if (e.key !== 'Tab') return;
      var f = focusable();
      if (!f.length) return;
      var first = f[0], last = f[f.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    });

    /* A menu pinned under the toolbar must not survive the switch to the
       desktop toolbar. */
    window.addEventListener('resize', function () {
      if (window.innerWidth >= 1024 && drawer.getAttribute('data-open') === 'true') {
        setDrawer(false);
      }
    });
  }

  /* ============================================================ carousels ==
     One engine, every carousel on the page. The markup is a scroll-snapping
     row, so this only has to move the scroll position: touch swipe, momentum
     and snapping are the browser's job.

     House rules: five seconds, and no play/pause control. It does stop while
     the reader is hovering, swiping or tabbing through it, and it does not
     auto-advance at all when the system asks for reduced motion — a carousel
     that fights the reader is worse than no carousel. */

  Array.prototype.forEach.call(document.querySelectorAll('[data-carousel]'), function (root) {
    var viewport = root.querySelector('[data-viewport]');
    var slides = Array.prototype.slice.call(root.querySelectorAll('[data-slide]'));
    var dots = Array.prototype.slice.call(root.querySelectorAll('[data-dot]'));
    var status = root.querySelector('[data-status]');
    var prev = root.querySelector('[data-prev]');
    var next = root.querySelector('[data-next]');
    if (!viewport || slides.length < 2) return;

    var interval = parseInt(root.getAttribute('data-interval'), 10) || 5000;
    var index = 0;
    var timer = null;
    var held = false;
    var scrollSettle = null;

    root.classList.add('is-enhanced');

    function sync() {
      slides.forEach(function (slide, i) {
        var on = i === index;
        slide.setAttribute('aria-hidden', on ? 'false' : 'true');
        var link = slide.querySelector('.cslide__link');
        if (link) {
          if (on) link.removeAttribute('tabindex');
          else link.setAttribute('tabindex', '-1');
        }
      });
      dots.forEach(function (dot, i) {
        var on = i === index;
        dot.setAttribute('aria-selected', on ? 'true' : 'false');
        dot.setAttribute('tabindex', on ? '0' : '-1');
      });
      if (status) status.textContent = 'Story ' + (index + 1) + ' of ' + slides.length;
    }

    function goTo(i, smooth) {
      index = (i + slides.length) % slides.length;
      var left = slides[index].offsetLeft - slides[0].offsetLeft;
      if (viewport.scrollTo) {
        viewport.scrollTo({ left: left, behavior: (smooth === false || reduced) ? 'auto' : 'smooth' });
      } else {
        viewport.scrollLeft = left;
      }
      sync();
    }

    function start() {
      stop();
      if (reduced || held) return;
      timer = window.setInterval(function () { goTo(index + 1); }, interval);
    }

    function stop() {
      if (timer) { window.clearInterval(timer); timer = null; }
    }

    function hold() { held = true; stop(); }
    function release() { held = false; start(); }

    /* Keep the dots honest when the reader swipes the row themselves. */
    viewport.addEventListener('scroll', function () {
      if (scrollSettle) window.clearTimeout(scrollSettle);
      scrollSettle = window.setTimeout(function () {
        var origin = slides[0].offsetLeft;
        var nearest = 0;
        var best = Infinity;
        slides.forEach(function (slide, i) {
          var d = Math.abs((slide.offsetLeft - origin) - viewport.scrollLeft);
          if (d < best) { best = d; nearest = i; }
        });
        if (nearest !== index) { index = nearest; sync(); }
      }, 120);
    }, { passive: true });

    if (prev) prev.addEventListener('click', function () { goTo(index - 1); start(); });
    if (next) next.addEventListener('click', function () { goTo(index + 1); start(); });

    dots.forEach(function (dot, i) {
      dot.addEventListener('click', function () { goTo(i); start(); });
      dot.addEventListener('keydown', function (e) {
        var to = null;
        if (e.key === 'ArrowRight') to = (i + 1) % dots.length;
        if (e.key === 'ArrowLeft') to = (i - 1 + dots.length) % dots.length;
        if (e.key === 'Home') to = 0;
        if (e.key === 'End') to = dots.length - 1;
        if (to === null) return;
        e.preventDefault();
        goTo(to);
        dots[to].focus();
        start();
      });
    });

    root.addEventListener('mouseenter', hold);
    root.addEventListener('mouseleave', release);
    root.addEventListener('focusin', hold);
    root.addEventListener('focusout', function (e) {
      if (!root.contains(e.relatedTarget)) release();
    });
    root.addEventListener('touchstart', hold, { passive: true });
    root.addEventListener('touchend', function () {
      window.setTimeout(release, 400);
    }, { passive: true });

    document.addEventListener('visibilitychange', function () {
      if (document.hidden) stop(); else start();
    });

    /* A resize changes how far one slide is; re-anchor without animating. */
    var resizeSettle = null;
    window.addEventListener('resize', function () {
      if (resizeSettle) window.clearTimeout(resizeSettle);
      resizeSettle = window.setTimeout(function () { goTo(index, false); }, 150);
    });

    sync();
    start();
  });

  /* ================================================= live-scores filters == */

  Array.prototype.forEach.call(document.querySelectorAll('[data-scorestrip]'), function (strip) {
    var buttons = Array.prototype.slice.call(strip.querySelectorAll('[data-filter]'));
    var cards = Array.prototype.slice.call(strip.querySelectorAll('.mcard'));
    var empty = strip.querySelector('[data-empty]');
    var track = strip.querySelector('.scorestrip__track');
    if (!buttons.length) return;

    buttons.forEach(function (button) {
      button.addEventListener('click', function () {
        var want = button.getAttribute('data-filter');
        buttons.forEach(function (b) {
          b.setAttribute('aria-pressed', b === button ? 'true' : 'false');
        });
        var shown = 0;
        cards.forEach(function (card) {
          var on = want === 'all' || card.getAttribute('data-sport') === want;
          if (on) { card.removeAttribute('hidden'); shown++; }
          else card.setAttribute('hidden', '');
        });
        if (empty) {
          if (shown) empty.setAttribute('hidden', '');
          else empty.removeAttribute('hidden');
        }
        if (track) track.scrollLeft = 0;
      });
    });
  });

  /* ================================================================ video ==
     Click-to-play. The page ships a still and a button; YouTube is only
     contacted once a reader asks for the video, and the player replaces the
     button inside the same fixed box so nothing on the page moves. */

  Array.prototype.forEach.call(document.querySelectorAll('[data-video]'), function (button) {
    button.addEventListener('click', function () {
      var id = button.getAttribute('data-video');
      if (!id) return;
      var frame = document.createElement('div');
      frame.className = 'vcard__frame';
      var iframe = document.createElement('iframe');
      iframe.src = 'https://www.youtube-nocookie.com/embed/' + encodeURIComponent(id) +
                   '?autoplay=1&rel=0&modestbranding=1';
      iframe.title = button.getAttribute('aria-label') || 'Video';
      iframe.allow = 'accelerometer; autoplay; encrypted-media; picture-in-picture';
      iframe.setAttribute('allowfullscreen', '');
      iframe.setAttribute('referrerpolicy', 'strict-origin-when-cross-origin');
      frame.appendChild(iframe);
      button.parentNode.replaceChild(frame, button);
      iframe.focus();
    });
  });

  /* ========================================================= scores board == */

  Array.prototype.forEach.call(document.querySelectorAll('[data-board]'), function (board) {
    var buttons = Array.prototype.slice.call(board.querySelectorAll('[data-board-filter]'));
    var groups = Array.prototype.slice.call(board.querySelectorAll('.board__sport'));
    var empty = board.querySelector('[data-board-empty]');
    if (!buttons.length) return;

    buttons.forEach(function (button) {
      button.addEventListener('click', function () {
        var want = button.getAttribute('data-board-filter');
        buttons.forEach(function (b) {
          b.setAttribute('aria-pressed', b === button ? 'true' : 'false');
        });
        var shown = 0;
        groups.forEach(function (group) {
          var on = want === 'all' || group.getAttribute('data-sport') === want;
          if (on) { group.removeAttribute('hidden'); shown++; }
          else group.setAttribute('hidden', '');
        });
        if (empty) {
          if (shown) empty.setAttribute('hidden', '');
          else empty.removeAttribute('hidden');
        }
      });
    });
  });

  /* ============================================================ copy link == */

  Array.prototype.forEach.call(document.querySelectorAll('[data-copy-link]'), function (btn) {
    btn.addEventListener('click', function () {
      var url = btn.getAttribute('data-copy-link');
      if (!navigator.clipboard || !navigator.clipboard.writeText) return;
      navigator.clipboard.writeText(url).then(function () {
        var previous = btn.getAttribute('aria-label');
        btn.setAttribute('aria-label', 'Link copied');
        btn.style.background = 'var(--c-win)';
        btn.style.borderColor = 'var(--c-win)';
        btn.style.color = '#fff';
        window.setTimeout(function () {
          btn.setAttribute('aria-label', previous);
          btn.style.background = '';
          btn.style.borderColor = '';
          btn.style.color = '';
        }, 1600);
      }).catch(function () {});
    });
  });
})();
